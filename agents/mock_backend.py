"""Deterministic offline backend used for demos, tests, and first-run setup."""
from __future__ import annotations

from typing import Any


class MockBackend:
    """Produces a simple, valid layout without calling an external model."""

    async def complete_json(
        self, *, system_prompt: str, input_data: dict[str, Any], agent_name: str
    ) -> dict[str, Any]:
        job = input_data.get("job", {})
        profile = input_data.get("profile", {})
        theme = str(job.get("theme", input_data.get("theme", "Bottle design")))
        width = int(profile.get("width_px", 9000))
        height = int(profile.get("height_px", 6000))

        if agent_name == "image_analysis":
            assets = input_data.get("reference_assets", []) + input_data.get("approved_assets", [])
            return {
                "assets": [
                    {"asset_id": item, "observations": ["Mock backend does not inspect image pixels."],
                     "likely_role": "user-supplied reference", "readability": "not assessed",
                     "technical_warnings": ["Replace mock analysis with a vision-enabled backend."]}
                    for item in assets
                ],
                "overall_notes": "Offline mock run; no image pixels were analyzed."
            }
        if agent_name == "theme_planner":
            return {
                "concept": f"{theme} — monochrome wrap",
                "visual_hierarchy": ["theme title", "decorative linework", "supporting copy"],
                "composition": {"direction": "horizontal wrap", "balance": "centered"},
                "style_rules": {"palette": ["#000000", "#FFFFFF"], "line_weight": "medium"},
                "avoid": ["unapproved claims", "invented brand assets"],
                "open_questions": []
            }
        if agent_name == "asset_placement":
            required = job.get("required_text", [])
            approved = job.get("approved_assets", [])
            return {
                "placements": [
                    {"asset_id": f"text-{index}", "role": "required_text", "content": text,
                     "anchor": "center", "relative_bounds": {"x": 0.2, "y": 0.35 + index * 0.08,
                     "width": 0.6, "height": 0.06}, "priority": "required"}
                    for index, text in enumerate(required)
                ] + [
                    {"asset_id": asset, "role": "approved_asset", "anchor": "center",
                     "relative_bounds": {"x": 0.4, "y": 0.55, "width": 0.2, "height": 0.2},
                     "priority": "required"} for asset in approved
                ],
                "missing_assets": [],
                "optional_unused_assets": []
            }
        if agent_name == "layout":
            elements = [
                {"id": "background", "type": "rect", "x": 0, "y": 0, "width": 1, "height": 1,
                 "fill": "#FFFFFF", "stroke": "#000000", "stroke_width": 0.002},
                {"id": "frame", "type": "rect", "x": 0.025, "y": 0.12, "width": 0.95,
                 "height": 0.76, "fill": "none", "stroke": "#000000", "stroke_width": 0.003},
                {"id": "title", "type": "text", "x": 0.5, "y": 0.48, "text": theme,
                 "font_size": 0.055, "anchor": "middle", "fill": "#000000"},
            ]
            for index, text in enumerate(job.get("required_text", [])):
                elements.append({"id": f"copy-{index}", "type": "text", "x": 0.5,
                                 "y": 0.60 + index * 0.055, "text": text,
                                 "font_size": 0.022, "anchor": "middle", "fill": "#000000"})
            return {
                "canvas": {"width_px": width, "height_px": height, "dpi": 1200,
                           "color_mode": "black-and-white"},
                "elements": elements,
                "safe_area": {"inset": 0.025},
                "seam_strategy": "Keep key content away from both wrap edges; verify seam on physical sample.",
                "render_notes": "Generated by deterministic mock backend; replace with AI-designed layout."
            }
        if agent_name == "quality_review":
            layout = input_data.get("layout_spec", {})
            canvas = layout.get("canvas", {})
            valid = (canvas.get("width_px") == width and canvas.get("height_px") == height
                     and canvas.get("dpi") == 1200)
            return {
                "passed": bool(valid),
                "issues": [] if valid else ["Canvas dimensions or DPI do not match the selected profile."],
                "warnings": ["Mock backend does not assess visual quality or raster asset resolution.",
                             "Printer seam, bleed, and safe area require physical verification."],
                "checks": {"profile_dimensions": {"passed": bool(valid)}},
                "recommendations": ["Review the generated preview before final-size export."]
            }
        raise ValueError(f"Mock backend does not implement agent: {agent_name}")
